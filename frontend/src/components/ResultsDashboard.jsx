import React, { useState } from 'react';
import CircularScore from './CircularScore';
import { 
  CheckCircle2, 
  XCircle, 
  Copy, 
  Check, 
  Printer, 
  ArrowLeft, 
  ChevronDown, 
  ChevronUp, 
  Award, 
  FolderGit2, 
  Briefcase, 
  HelpCircle, 
  AlertTriangle,
  Lightbulb,
  FileText
} from 'lucide-react';

/**
 * Renders the full resume analysis dashboard including scores, strengths, 
 * weaknesses, missing skills, target roles, and mock interview questions.
 */
export default function ResultsDashboard({ data, fileName, onReset }) {
  const [copiedSummary, setCopiedSummary] = useState(false);
  const [copiedAll, setCopiedAll] = useState(false);
  const [activeQuestion, setActiveQuestion] = useState(null);

  const overall_score = typeof data?.overall_score === 'number' ? data.overall_score : 0;
  const ats_score = typeof data?.ats_score === 'number' ? data.ats_score : 0;
  const grammar_score = typeof data?.grammar_score === 'number' ? data.grammar_score : 0;
  const skills_score = typeof data?.skills_score === 'number' ? data.skills_score : 0;

  const strengths = Array.isArray(data?.strengths) ? data.strengths : [];
  const weaknesses = Array.isArray(data?.weaknesses) ? data.weaknesses : [];
  const missing_skills = Array.isArray(data?.missing_skills) ? data.missing_skills : [];
  const recommended_projects = Array.isArray(data?.recommended_projects) ? data.recommended_projects : [];
  const recommended_certifications = Array.isArray(data?.recommended_certifications) ? data.recommended_certifications : [];
  const best_job_roles = Array.isArray(data?.best_job_roles) ? data.best_job_roles : [];
  const interview_questions = Array.isArray(data?.interview_questions) ? data.interview_questions : [];
  const final_suggestions = Array.isArray(data?.final_suggestions) ? data.final_suggestions : [];

  const resume_summary = typeof data?.resume_summary === 'string' ? data.resume_summary : "";
  const improved_summary = typeof data?.improved_summary === 'string' ? data.improved_summary : "";

  const handleCopySummary = () => {
    if (!improved_summary) return;
    navigator.clipboard.writeText(improved_summary);
    setCopiedSummary(true);
    setTimeout(() => setCopiedSummary(false), 2000);
  };

  const handleCopyAll = () => {
    const formattedText = `
RESUME ANALYSIS REPORT: ${fileName}
==========================================
Overall Score: ${overall_score}/100
ATS Score: ${ats_score}/100
Grammar Score: ${grammar_score}/100
Skills Score: ${skills_score}/100

STRENGTHS:
${strengths.map(s => `- ${s}`).join('\n')}

AREAS OF IMPROVEMENT:
${weaknesses.map(w => `- ${w}`).join('\n')}

MISSING KEYWORDS/SKILLS:
${missing_skills.map(sk => `- ${sk}`).join('\n')}

BEST JOB ROLES TO TARGET:
${best_job_roles.map(r => `- ${r}`).join('\n')}

RECOMMENDED PROJECTS:
${recommended_projects.map(p => `- ${p}`).join('\n')}

RECOMMENDED CERTIFICATIONS:
${recommended_certifications.map(c => `- ${c}`).join('\n')}

IMPROVED PROFESSIONAL SUMMARY:
${improved_summary}

MOCK INTERVIEW QUESTIONS:
${interview_questions.map(q => `- ${q}`).join('\n')}

ACTIONABLE SUGGESTIONS:
${final_suggestions.map(f => `- ${f}`).join('\n')}
==========================================
Generated by ResuMind AI
    `;
    navigator.clipboard.writeText(formattedText.trim());
    setCopiedAll(true);
    setTimeout(() => setCopiedAll(false), 2000);
  };

  const handlePrint = () => {
    window.print();
  };

  const toggleQuestion = (index) => {
    setActiveQuestion(activeQuestion === index ? null : index);
  };

  return (
    <div className="max-w-6xl mx-auto px-4 pb-24 animate-fade-in print-container">
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 mb-8 no-print">
        <button
          onClick={onReset}
          className="flex items-center gap-2 text-sm font-semibold text-slate-500 hover:text-slate-800 dark:text-slate-400 dark:hover:text-slate-200 transition-colors cursor-pointer group"
        >
          <ArrowLeft className="h-4 w-4 group-hover:-translate-x-0.5 transition-transform" />
          <span>Analyze another resume</span>
        </button>

        <div className="flex flex-wrap gap-3">
          <button
            onClick={handleCopyAll}
            className="flex items-center gap-2 py-2.5 px-4 rounded-xl border border-slate-200/50 dark:border-slate-800/40 bg-white/70 dark:bg-slate-900/60 backdrop-blur-sm text-sm font-bold text-slate-700 dark:text-slate-200 hover:bg-slate-50 dark:hover:bg-slate-800 transition-colors shadow-sm cursor-pointer"
          >
            {copiedAll ? (
              <>
                <Check className="h-4.5 w-4.5 text-emerald-500" />
                <span className="text-emerald-500">Report Copied!</span>
              </>
            ) : (
              <>
                <Copy className="h-4.5 w-4.5" />
                <span>Copy Full Report</span>
              </>
            )}
          </button>

          <button
            onClick={handlePrint}
            className="flex items-center gap-2 py-2.5 px-4 rounded-xl bg-gradient-to-r from-indigo-600 to-indigo-700 hover:from-indigo-500 hover:to-indigo-600 text-white text-sm font-bold shadow-md shadow-indigo-500/10 hover:shadow-indigo-500/20 transition-all cursor-pointer"
          >
            <Printer className="h-4.5 w-4.5" />
            <span>Download Analysis (PDF)</span>
          </button>
        </div>
      </div>

      <div className="mb-8 border-b border-slate-200/60 dark:border-slate-800/50 pb-6 print-full-width">
        <h1 className="text-3xl font-extrabold font-outfit text-slate-900 dark:text-white print-text-dark">
          Resume Analysis Results
        </h1>
        <p className="text-sm text-slate-500 dark:text-slate-400 mt-1">
          File Name: <span className="font-semibold text-slate-700 dark:text-slate-300">{fileName}</span>
        </p>
      </div>

      <div className="grid grid-cols-2 md:grid-cols-4 gap-4 mb-8 print-grid">
        <CircularScore 
          score={overall_score} 
          label="Overall Score" 
          colors={{ text: 'text-indigo-600', ring: 'stroke-indigo-500 dark:stroke-indigo-400', glow: 'glass-glow-indigo' }}
          delay={0}
        />
        <CircularScore 
          score={ats_score} 
          label="ATS Compatibility" 
          colors={{ text: 'text-emerald-600', ring: 'stroke-emerald-500 dark:stroke-emerald-400', glow: 'glass-glow-emerald' }}
          delay={200}
        />
        <CircularScore 
          score={grammar_score} 
          label="Grammar & Style" 
          colors={{ text: 'text-amber-600', ring: 'stroke-amber-500 dark:stroke-amber-400', glow: 'shadow-amber-500/5' }}
          delay={400}
        />
        <CircularScore 
          score={skills_score} 
          label="Skills Match" 
          colors={{ text: 'text-blue-600', ring: 'stroke-blue-500 dark:stroke-blue-400', glow: 'shadow-blue-500/5' }}
          delay={600}
        />
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 gap-6 mb-8 print-grid">
        <div className="glass-panel rounded-3xl p-6 border-slate-200/50 dark:border-slate-800/40">
          <h2 className="text-xl font-bold font-outfit text-slate-900 dark:text-white flex items-center gap-2 mb-4 print-text-dark">
            <CheckCircle2 className="h-5.5 w-5.5 text-emerald-500 shrink-0" />
            <span>Key Strengths</span>
          </h2>
          <ul className="space-y-3">
            {strengths.length > 0 ? (
              strengths.map((str, i) => (
                <li key={i} className="flex items-start gap-2.5 text-sm text-slate-600 dark:text-slate-300 leading-normal">
                  <span className="h-2 w-2 rounded-full bg-emerald-500 mt-2 shrink-0"></span>
                  <span>{str}</span>
                </li>
              ))
            ) : (
              <p className="text-sm text-slate-400">No core strengths highlighted.</p>
            )}
          </ul>
        </div>

        <div className="glass-panel rounded-3xl p-6 border-slate-200/50 dark:border-slate-800/40">
          <h2 className="text-xl font-bold font-outfit text-slate-900 dark:text-white flex items-center gap-2 mb-4 print-text-dark">
            <AlertTriangle className="h-5.5 w-5.5 text-rose-500 shrink-0" />
            <span>Areas of Improvement</span>
          </h2>
          <ul className="space-y-3">
            {weaknesses.length > 0 ? (
              weaknesses.map((weak, i) => (
                <li key={i} className="flex items-start gap-2.5 text-sm text-slate-600 dark:text-slate-300 leading-normal">
                  <span className="h-2 w-2 rounded-full bg-rose-500 mt-2 shrink-0"></span>
                  <span>{weak}</span>
                </li>
              ))
            ) : (
              <p className="text-sm text-slate-400">No major weaknesses identified.</p>
            )}
          </ul>
        </div>

        <div className="glass-panel rounded-3xl p-6 border-slate-200/50 dark:border-slate-800/40">
          <h2 className="text-xl font-bold font-outfit text-slate-900 dark:text-white flex items-center gap-2 mb-4 print-text-dark">
            <Lightbulb className="h-5.5 w-5.5 text-amber-500 shrink-0" />
            <span>Missing Industry Keywords / Skills</span>
          </h2>
          <p className="text-xs text-slate-400 dark:text-slate-500 mb-4 uppercase tracking-widest font-bold">
            Add these to bypass automated ATS filters
          </p>
          <div className="flex flex-wrap gap-2">
            {missing_skills.length > 0 ? (
              missing_skills.map((skill, i) => (
                <span 
                  key={i} 
                  className="py-1.5 px-3 rounded-xl bg-amber-500/10 border border-amber-500/20 text-amber-600 dark:text-amber-400 text-xs font-bold font-outfit tracking-wide shadow-sm"
                >
                  {skill}
                </span>
              ))
            ) : (
              <p className="text-sm text-slate-400">Excellent! No missing essential skills detected.</p>
            )}
          </div>
        </div>

        <div className="glass-panel rounded-3xl p-6 border-slate-200/50 dark:border-slate-800/40">
          <h2 className="text-xl font-bold font-outfit text-slate-900 dark:text-white flex items-center gap-2 mb-4 print-text-dark">
            <Briefcase className="h-5.5 w-5.5 text-indigo-500 shrink-0" />
            <span>Best Job Roles to Target</span>
          </h2>
          <p className="text-xs text-slate-400 dark:text-slate-500 mb-4 uppercase tracking-widest font-bold">
            Positions that align with your experience
          </p>
          <div className="flex flex-wrap gap-2">
            {best_job_roles.length > 0 ? (
              best_job_roles.map((role, i) => (
                <span 
                  key={i} 
                  className="py-1.5 px-3 rounded-xl bg-indigo-500/10 border border-indigo-500/20 text-indigo-600 dark:text-indigo-400 text-xs font-bold font-outfit tracking-wide shadow-sm"
                >
                  {role}
                </span>
              ))
            ) : (
              <p className="text-sm text-slate-400 font-medium">No target roles extracted.</p>
            )}
          </div>
        </div>
      </div>

      <div className="glass-panel rounded-3xl p-6 border-slate-200/50 dark:border-slate-800/40 mb-8 print-full-width">
        <h2 className="text-xl font-bold font-outfit text-slate-900 dark:text-white flex items-center gap-2 mb-6 print-text-dark">
          <FileText className="h-5.5 w-5.5 text-indigo-500 shrink-0" />
          <span>Professional Summary Optimization</span>
        </h2>

        <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
          {resume_summary && (
            <div className="p-5 rounded-2xl bg-slate-100/50 dark:bg-slate-900/40 border border-slate-200/20 dark:border-slate-800/30">
              <h3 className="text-xs font-bold text-slate-400 dark:text-slate-500 uppercase tracking-widest mb-3">
                Original Summary
              </h3>
              <p className="text-sm text-slate-600 dark:text-slate-400 leading-relaxed font-normal">
                {resume_summary}
              </p>
            </div>
          )}

          <div className={`p-5 rounded-2xl bg-indigo-500/5 border border-indigo-500/10 dark:border-indigo-800/20 relative ${!resume_summary ? 'lg:col-span-2' : ''}`}>
            <div className="flex items-center justify-between mb-3 no-print">
              <h3 className="text-xs font-bold text-indigo-600 dark:text-indigo-400 uppercase tracking-widest">
                AI-Improved Summary (Recommended)
              </h3>
              <button
                onClick={handleCopySummary}
                className="flex items-center gap-1.5 py-1 px-2.5 rounded-lg bg-white dark:bg-slate-800 border border-slate-200/50 dark:border-slate-700/40 text-xs font-semibold text-slate-600 dark:text-slate-300 hover:text-indigo-600 dark:hover:text-indigo-400 transition-colors shadow-xs cursor-pointer"
              >
                {copiedSummary ? (
                  <>
                    <Check className="h-3.5 w-3.5 text-emerald-500" />
                    <span className="text-emerald-500">Copied!</span>
                  </>
                ) : (
                  <>
                    <Copy className="h-3.5 w-3.5" />
                    <span>Copy</span>
                  </>
                )}
              </button>
            </div>
            
            <h3 className="text-xs font-bold text-indigo-600 dark:text-indigo-400 uppercase tracking-widest mb-3 hidden print:block">
              AI-Improved Summary (Recommended)
            </h3>
            
            <p className="text-sm text-slate-700 dark:text-slate-300 leading-relaxed font-medium">
              {improved_summary || "Could not generate an optimized summary."}
            </p>
          </div>
        </div>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 gap-6 mb-8 print-grid">
        <div className="glass-panel rounded-3xl p-6 border-slate-200/50 dark:border-slate-800/40">
          <h2 className="text-xl font-bold font-outfit text-slate-900 dark:text-white flex items-center gap-2 mb-4 print-text-dark">
            <FolderGit2 className="h-5.5 w-5.5 text-indigo-500 shrink-0" />
            <span>Recommended Projects</span>
          </h2>
          <p className="text-xs text-slate-400 dark:text-slate-500 mb-4 uppercase tracking-widest font-bold">
            Build these to strengthen your skill demonstration
          </p>
          <ul className="space-y-4">
            {recommended_projects.length > 0 ? (
              recommended_projects.map((proj, i) => (
                <li key={i} className="flex gap-3 leading-normal">
                  <div className="mt-1 h-5 w-5 shrink-0 rounded-lg bg-indigo-500/10 flex items-center justify-center text-indigo-600 dark:text-indigo-400 text-xs font-bold font-outfit">
                    {i + 1}
                  </div>
                  <span className="text-sm text-slate-600 dark:text-slate-300 font-medium">{proj}</span>
                </li>
              ))
            ) : (
              <p className="text-sm text-slate-400">No custom projects suggested.</p>
            )}
          </ul>
        </div>

        <div className="glass-panel rounded-3xl p-6 border-slate-200/50 dark:border-slate-800/40">
          <h2 className="text-xl font-bold font-outfit text-slate-900 dark:text-white flex items-center gap-2 mb-4 print-text-dark">
            <Award className="h-5.5 w-5.5 text-purple-500 shrink-0" />
            <span>Recommended Certifications</span>
          </h2>
          <p className="text-xs text-slate-400 dark:text-slate-500 mb-4 uppercase tracking-widest font-bold">
            Credentials to boost your job applications
          </p>
          <ul className="space-y-4">
            {recommended_certifications.length > 0 ? (
              recommended_certifications.map((cert, i) => (
                <li key={i} className="flex gap-3 leading-normal">
                  <div className="mt-1 h-5 w-5 shrink-0 rounded-lg bg-purple-500/10 flex items-center justify-center text-purple-600 dark:text-purple-400 text-xs font-bold font-outfit">
                    {i + 1}
                  </div>
                  <span className="text-sm text-slate-600 dark:text-slate-300 font-medium">{cert}</span>
                </li>
              ))
            ) : (
              <p className="text-sm text-slate-400">No specific certifications suggested.</p>
            )}
          </ul>
        </div>
      </div>

      <div className="glass-panel rounded-3xl p-6 border-slate-200/50 dark:border-slate-800/40 mb-8 print-full-width">
        <h2 className="text-xl font-bold font-outfit text-slate-900 dark:text-white flex items-center gap-2 mb-4 print-text-dark">
          <HelpCircle className="h-5.5 w-5.5 text-blue-500 shrink-0" />
          <span>Interactive Mock Interview Practice</span>
        </h2>
        <p className="text-xs text-slate-400 dark:text-slate-500 mb-6 uppercase tracking-widest font-bold no-print">
          Click on any question to reflect on your answers
        </p>

        <p className="text-xs text-slate-400 dark:text-slate-500 mb-6 uppercase tracking-widest font-bold hidden print:block">
          Practice questions based on your experience
        </p>

        <div className="space-y-3">
          {interview_questions.length > 0 ? (
            interview_questions.map((q, i) => (
              <div 
                key={i} 
                className="rounded-2xl border border-slate-100 dark:border-slate-800 bg-white/50 dark:bg-slate-900/30 overflow-hidden transition-all shadow-xs"
              >
                <button
                  onClick={() => toggleQuestion(i)}
                  className="w-full flex items-center justify-between gap-4 p-4 text-left font-semibold text-sm text-slate-700 dark:text-slate-200 hover:bg-slate-50 dark:hover:bg-slate-800/40 transition-colors cursor-pointer"
                >
                  <span className="font-medium font-outfit pr-2">{q}</span>
                  <span className="shrink-0 text-slate-400 dark:text-slate-500 no-print">
                    {activeQuestion === i ? (
                      <ChevronUp className="h-4.5 w-4.5" />
                    ) : (
                      <ChevronDown className="h-4.5 w-4.5" />
                    )}
                  </span>
                </button>
                
                <div 
                  className={`transition-all duration-300 overflow-hidden no-print ${
                    activeQuestion === i ? 'max-h-40 border-t border-slate-100 dark:border-slate-800' : 'max-h-0'
                  }`}
                >
                  <div className="p-4 bg-slate-50/50 dark:bg-slate-900/10 text-xs text-slate-500 dark:text-slate-400 leading-relaxed font-normal">
                    <span className="font-bold text-indigo-500 dark:text-indigo-400 uppercase tracking-wide block mb-1">
                      Coaching Tip:
                    </span>
                    When answering, use the STAR method (Situation, Task, Action, Result). Highlight quantitative accomplishments from your resume that directly answer this prompt.
                  </div>
                </div>

                <div className="hidden print:block p-4 border-t border-slate-100 text-xs text-slate-600 leading-relaxed">
                  <span className="font-bold text-indigo-600 uppercase tracking-wide block mb-1">Coaching Tip:</span>
                  Structure your answer around the STAR method: describe a specific Situation/Task, the Actions you took, and the quantifiable Results achieved.
                </div>
              </div>
            ))
          ) : (
            <p className="text-sm text-slate-400">No custom questions available.</p>
          )}
        </div>
      </div>

      <div className="glass-panel rounded-3xl p-6 border-slate-200/50 dark:border-slate-800/40 print-full-width">
        <h2 className="text-xl font-bold font-outfit text-slate-900 dark:text-white flex items-center gap-2 mb-5 print-text-dark">
          <Lightbulb className="h-5.5 w-5.5 text-indigo-500 shrink-0" />
          <span>Final Next Steps</span>
        </h2>
        <ul className="space-y-4">
          {final_suggestions.length > 0 ? (
            final_suggestions.map((suggestion, i) => (
              <li key={i} className="flex gap-3 leading-normal">
                <div className="mt-0.5 h-6 w-6 shrink-0 rounded-full bg-indigo-500/10 flex items-center justify-center text-indigo-600 dark:text-indigo-400 text-xs font-extrabold font-outfit">
                  {i + 1}
                </div>
                <span className="text-sm text-slate-600 dark:text-slate-300 font-medium">{suggestion}</span>
              </li>
            ))
          ) : (
            <p className="text-sm text-slate-400">No suggestions available.</p>
          )}
        </ul>
      </div>

      <div className="mt-12 flex justify-center no-print">
        <button
          onClick={onReset}
          className="flex items-center gap-2 py-3 px-6 rounded-2xl bg-slate-200/60 dark:bg-slate-900/60 text-slate-700 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white hover:bg-slate-300/60 dark:hover:bg-slate-800/60 text-sm font-bold shadow-md transition-colors cursor-pointer"
        >
          <ArrowLeft className="h-4.5 w-4.5" />
          <span>Analyze another resume</span>
        </button>
      </div>
    </div>
  );
}
